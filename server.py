# The shorts feed rescans the archive on every request (~1 s for ~19k files on
# an external drive), and the feed refills after only a couple of swipes -- so
# without a cache each swipe cost a full directory walk. The result is held
# briefly: a clip downloaded a moment ago shows up within the TTL, and an
# explicit refresh bypasses it entirely.
_SCAN_TTL = 15.0
_scan_cache: dict = {"t": 0.0, "root": None, "found": None}
_scan_lock = threading.Lock()

# Static-video scan: a background job, because a full pass over an archive is
# minutes to hours of decoding and the page must not sit and wait for it. Same
# shape as the download queue on purpose -- a phase, a count, a cancel flag and
# a last result -- so the UI can show real progress instead of a frozen button.
_static_job: dict = {
    "running": False, "cancelled": False, "phase": "", "checked": 0,
    "total": 0, "found": [], "images": 0, "error": "", "done": False,
    "text": "", "started": 0.0, "scope": "",
}
_static_lock = threading.Lock()


def _scan_clips(root, force: bool = False):
    import shorts
    now = time.time()
    with _scan_lock:
        c = _scan_cache
        if (not force and c["found"] is not None and c["root"] == str(root)
                and (now - c["t"]) < _SCAN_TTL):
            return c["found"]
        db = _profile_db()
        found = shorts.scan(root, known_reels=db.known_reels(),
                            known_reels_cache=db)
        c.update(t=now, root=str(root), found=found)
        return found


def _invalidate_scan():
    """Drop the cached scan, e.g. just after a download finishes."""
    with _scan_lock:
        _scan_cache["found"] = None


def _static_scan_worker(scope: str, write_images: bool) -> None:
    """Walk the archive looking for clips whose frames never change.

    Runs on its own thread. Progress is written into _static_job, which is what
    the UI polls -- there is no other channel, and holding a request open for
    hours would time out long before it finished.
    """
    import static_videos as sv          # tools/, put on the path at import time
    eng = get_engine()
    try:
        rows = list(sv.videos_for_scan(Path(eng.output_root),
                                       stories_only=(scope == "stories")))
        with _static_lock:
            _static_job["total"] = len(rows)
            _static_job["phase"] = "scanning"
        found = []
        for fp, folder, size, story in rows:
            with _static_lock:
                if _static_job["cancelled"]:
                    _static_job["phase"] = "cancelled"
                    return
                _static_job["checked"] += 1
                _static_job["text"] = f"{folder.name}/{fp.name}"
            stats = sv.frame_stats(fp)
            if stats is None:
                continue
            _n, diff = stats
            if diff > sv.STATIC_THRESHOLD:
                continue
            dur = sv.duration_of(fp)
            row = {"path": str(fp), "profile": folder.name, "name": fp.name,
                   "bytes": size, "mean_diff": round(diff, 3),
                   "seconds": round(dur, 1), "story": story, "image": ""}
            if write_images:
                dest = sv.still_path(folder, fp)
                if sv.extract_frame(fp, dest):
                    row["image"] = str(dest)
                    with _static_lock:
                        _static_job["images"] += 1
            found.append(row)
            with _static_lock:
                _static_job["found"] = found
        with _static_lock:
            _static_job["phase"] = "done"
    except Exception as e:
        with _static_lock:
            _static_job["phase"] = "error"
            _static_job["error"] = f"{type(e).__name__}: {e}"
    finally:
        with _static_lock:
            _static_job["running"] = False
            _static_job["done"] = True


def _static_write_from_findings() -> None:
    """Write still images for what the last scan already found.

    Deliberately not a second scan: the decode is the expensive part and its
    answer has not changed since a moment ago. The video is never touched -- an
    image is written beside it.
    """
    import static_videos as sv
    try:
        with _static_lock:
            rows = list(_static_job["found"])
            _static_job.update(running=True, cancelled=False, phase="writing",
                               images=0, done=False, error="")
        written = []
        for row in rows:
            with _static_lock:
                if _static_job["cancelled"]:
                    _static_job["phase"] = "cancelled"
                    return
                _static_job["text"] = f"{row['profile']}/{row['name']}"
            fp = Path(row["path"])
            if not fp.is_file():
                continue
            dest = sv.still_path(fp.parent, fp)
            if sv.extract_frame(fp, dest):
                row = dict(row, image=str(dest))
                written.append(row)
                with _static_lock:
                    _static_job["images"] = len(written)
        with _static_lock:
            _static_job["found"] = written
            _static_job["phase"] = "done"
    except Exception as e:
        with _static_lock:
            _static_job["phase"] = "error"
            _static_job["error"] = f"{type(e).__name__}: {e}"
    finally:
        with _static_lock:
            _static_job["running"] = False
            _static_job["done"] = True


def _static_delete_videos(dry_run: bool = False) -> dict:
    """Delete the video for every clip whose still image was written.

    Only ever a clip with a written image, and only the video: the image stays,
    and the sidecars stay so the post is not re-fetched. Nothing here guesses --
    a clip with no image is left alone, even if it was flagged, because deleting
    the video would then lose the content entirely.

    Follows the trash flow's own rule for the same reason: a 0-byte placeholder
    of the same name is left in the folder so instaloader's fast-update still
    sees the post as downloaded. Without it the next scan of that profile would
    pull the deleted video straight back down.
    """
    eng = get_engine()
    with _static_lock:
        rows = list(_static_job["found"])
    doomed = [r for r in rows if r.get("image") and Path(r["path"]).is_file()]
    freed = 0
    removed, errors = [], []
    for row in doomed:
        fp = Path(row["path"])
        try:
            size = fp.stat().st_size
        except OSError:
            continue
        if dry_run:
            freed += size
            removed.append(row["name"])
            continue
        try:
            # Placeholder first, mirroring clear_trash: if the unlink then fails
            # the post is still marked as having been fetched.
            placeholder = fp.parent / fp.name
            with open(placeholder, "wb"):
                pass
            fp.unlink()
            freed += size
            removed.append(row["name"])
            with eng.lock:
                eng.tombstones.append({
                    "username": row["profile"], "name": row["name"],
                    "at": time.time(),
                    "platform": "tiktok" if "/tiktok/" in str(fp) else "instagram",
                })
        except OSError as e:
            errors.append(f"{row['name']}: {e}")
    if not dry_run and removed:
        try:
            eng.save_state()
        except Exception:
            pass
        # The listing cache for those folders is stale now.
        for folder in {str(Path(r["path"]).parent) for r in doomed}:
            try:
                _cache.drop(folder)
                _media_cache_forget(Path(folder))
            except Exception:
                pass
        _invalidate_scan()
    return {"ok": True, "deleted": len(removed) if not dry_run else 0,
            "would_delete": len(removed), "bytes": freed,
            "names": removed[:50], "errors": errors[:20]}


def _static_remove(paths: list[str], keep_image: bool) -> dict:
    """Delete videos the scan found, leaving tombstones so they are not refetched.

    Writes a 0-byte placeholder in place of each video first, exactly as the
    trash flow does, because instaloader's fast-update treats 'the file exists'
    as 'already downloaded'. Without it, the next run would fetch the clip again
    and the deletion would silently undo itself.

    `keep_image` decides the still: True removes only the video and keeps the
    image beside it (the point of the feature -- you get one picture instead of a
    30-second clip of one picture), False removes the image too.

    Every path is checked before anything is removed: it must sit inside this
    archive, must not be a symlink, and must be a video that the scan itself
    reported. A path arriving from the browser is untrusted input, and this
    deletes files.
    """
    eng = get_engine()
    root = Path(eng.output_root).resolve()
    with _static_lock:
        known = {r["path"]: dict(r) for r in _static_job["found"]}
    removed = kept_images = 0
    errors: list[str] = []
    freed = 0
    for raw in paths:
        try:
            fp = Path(raw)
            if str(fp) not in known:
                errors.append(f"{fp.name}: not from the current scan")
                continue
            real = fp.resolve()
            if not real.is_file():
                continue
            # Must be inside the archive, and not a symlink pointing elsewhere.
            if root not in real.parents or fp.is_symlink():
                errors.append(f"{fp.name}: outside the archive, skipped")
                continue
            profile_dir = real.parent
            size = real.stat().st_size
            # Record the tombstone BEFORE removing anything, so a failure part-way
            # still leaves the post protected from a re-download.
            with _static_lock:
                eng.tombstones.append({
                    "username": profile_dir.name, "name": real.name,
                    "at": time.time(),
                    "platform": "tiktok" if profile_dir.parent.name == "tiktok"
                                else "instagram",
                })
                if len(eng.tombstones) > 5000:
                    del eng.tombstones[:-5000]
            import engine as _eng_mod
            # The placeholder is written AFTER the trash call, not before. It has
            # to be: the placeholder IS this path, so writing it first just meant
            # the trash took it away again and the video came back on the next
            # download run. Verified the hard way -- the file was gone entirely
            # with the tombstone recorded, which is the one state that must not
            # happen.
            for sib in profile_dir.glob(f"{real.stem}.*"):
                # Sidecars travel with their video, as in the trash flow.
                if sib.is_file() and not sib.is_symlink() and sib.suffix in (".json", ".txt", ".xz"):
                    _eng_mod._to_desktop_trash(sib)
                elif (not keep_image and sib.is_file() and not sib.is_symlink()
                      and sib.name.startswith(real.stem + "_still")):
                    _eng_mod._to_desktop_trash(sib)
            _eng_mod._to_desktop_trash(real)
            # Re-create the 0-byte placeholder instaloader's fast-update checks:
            # it treats 'the file exists' as 'already downloaded', so without this
            # the clip is fetched again and the deletion undoes itself.
            try:
                if not real.exists():
                    real.parent.mkdir(parents=True, exist_ok=True)
                    real.write_bytes(b"")
            except OSError as e:
                errors.append(f"{fp.name}: removed but placeholder failed ({e})")
            removed += 1
            freed += size
            if keep_image:
                kept_images += 1
        except OSError as e:
            errors.append(f"{Path(raw).name}: {e}")
    if removed:
        eng.save_state()
        _media_cache_forget(root)
    return {"ok": True, "removed": removed, "images_kept": kept_images,
            "bytes": freed, "errors": errors}


def count_param(body: dict, default: int = 5) -> int:
    """`count` from a request body, where 0 means "every video".

    The obvious `int(body.get("count") or 5)` reads 0 as "missing" and silently
    substitutes the default, so the selector's "All" option queued the newest
    five instead. Only a missing or blank value takes the default; a negative
    number is clamped to 0, which is the same request.
    """
    raw = body.get("count")
    if raw is None or raw == "":
        return default
    try:
        return max(0, int(raw))
    except (TypeError, ValueError):
        return default


def route_lines(text: str, fallback: str = "instagram") -> tuple[list[str], list[str]]:
    """Split a mixed paste into (instagram lines, tiktok lines).

    A line is routed by the link it contains, because that is the only reliable
    signal: the same handle can be two different people on the two sites, so a
    bare name cannot be guessed at. Bare names therefore follow `fallback` --
    the platform tab that was open -- so the result stays predictable rather than
    the app quietly picking a site for you.

    Commas split too, matching the Instagram box's long-standing behaviour.
    """
    ig: list[str] = []
    tt: list[str] = []
    for raw in (text or "").replace(",", "\n").splitlines():
        line = raw.strip()
        if not line:
            continue
        low = line.lower()
        if "tiktok.com" in low:
            tt.append(line)
        elif "instagram.com" in low:
            ig.append(line)
        elif fallback == "tiktok":
            tt.append(line)
        else:
            ig.append(line)
    return ig, tt


def _tt_raise_all(eng, step: int, scope: str = "finished") -> dict:
    """Raise the grab-count of every finished TikTok profile by `step`.

    One lock and one save for the whole batch, so the list cannot end up showing
    some profiles raised and others not after a partial apply. A profile already
    asking for its whole archive is left alone rather than queued for nothing.

    Anything already downloaded is kept: yt-dlp's archive file records what was
    fetched, so going 5 -> 10 pulls five more, not ten again.
    """
    touched = revived = at_total = 0
    with eng.lock:
        for job in eng.jobs.values():
            if getattr(job, "platform", "") != "tiktok":
                continue
            if getattr(job, "kind", "main") == "saved":
                # The saved pass is a link list, not a profile: there is no
                # "newest N" to raise, and a count here would silently cap it.
                continue
            if scope == "finished" and job.status not in (
                    "done", "failed", "cancelled", "skipped"):
                continue
            current = int(getattr(job, "tiktok_count", 0) or 0)
            total = int(getattr(job, "tiktok_total", 0) or 0)
            new_count = (current or 0) + step
            if total and new_count > total:
                new_count = total        # more than exists simply means all of it
            if new_count == current:
                at_total += 1
                continue
            job.tiktok_count = new_count
            if job.status in ("done", "failed", "cancelled", "skipped"):
                job.status = "queued"
                job.finished_at = None
                job.error = ""
                job.message = "queued for more videos"
                job.fatal = False
                revived += 1
                if job.id in eng.pending:
                    eng.pending.remove(job.id)
                eng.pending.insert(0, job.id)
            touched += 1
    eng.save_state()
    return {"ok": True, "changed": touched, "revived": revived,
            "already_at_total": at_total, "add": step}


def static_status() -> dict:
    """Snapshot of the static-video scan, for the UI to poll."""
    with _static_lock:
        j = dict(_static_job)
    j["found_count"] = len(j.get("found") or [])
    j["bytes"] = sum(r.get("bytes", 0) for r in (j.get("found") or []))
    # Only the newest few rows come back to the browser; the rest stay server-side
    # so a scan that finds hundreds does not push a huge payload every second.
    j["found"] = (j.get("found") or [])[-40:]
    return j


def _systemctl(*args) -> tuple[int, str]:
    try:
        r = subprocess.run(["systemctl", "--user", *args],
                           capture_output=True, text=True, timeout=10)
        return r.returncode, (r.stdout + r.stderr).strip()
    except Exception as e:
        return 1, str(e)


# The unit this app is normally installed as. "Start on login" is exactly
# systemd's idea of that unit being enabled, so it is read and set through
# systemctl instead of kept in our own settings: a second copy would drift the
# moment anyone used the terminal.
SERVICE_UNIT = "hardlywatching.service"


def autostart_state() -> dict:
    rc, out = _systemctl("is-enabled", SERVICE_UNIT)
    state = (out.splitlines() or [""])[0].strip()
    if state in ("", "not-found") or "No such" in out or "not found" in out.lower():
        return {"ok": True, "supported": False, "enabled": False, "state": state or "absent"}
    return {"ok": True, "supported": True, "enabled": state == "enabled", "state": state}


def set_autostart(want: bool) -> dict:
    rc, out = _systemctl("enable" if want else "disable", SERVICE_UNIT)
    st = autostart_state()
    if rc != 0 and not st.get("supported"):
        return {**st, "ok": False,
                "error": "Not running as a service, so there is nothing to enable. "
                         "Install it with install-service.sh first."}
    return {**st, "ok": rc == 0, "error": "" if rc == 0 else out}


def _open_folder(path: Path) -> None:
    """Reveal a folder in the desktop's file manager, on any OS."""
    if not path.exists():
        return
    if sys.platform == "darwin":
        cmds = [["open", str(path)]]
    elif os.name == "nt":
        cmds = [["explorer", str(path)]]
    else:
        cmds = [["xdg-open", str(path)], ["gio", "open", str(path)]]
    for cmd in cmds:
        try:
            subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return
        except FileNotFoundError:
            continue


def _find_terminal() -> list[str] | None:
    """Return argv prefix for the available terminal, or None.

    Each emulator takes a different flag for 'run this command', so the
    mapping matters -- ptyxis/gnome-terminal use `--`, most others use `-e`.
    """
    import shutil as _sh
    # (binary, how to pass a command)
    candidates = [
        ("ptyxis", "--"),
        ("kgx", "--"),
        ("gnome-terminal", "--"),
        ("konsole", "-e"),
        ("xfce4-terminal", "-e"),
        ("tilix", "-e"),
        ("mate-terminal", "-e"),
        ("lxterminal", "-e"),
        ("alacritty", "-e"),
        ("kitty", "-e"),
        ("wezterm", "start", "--"),
        ("foot", "-e"),
        ("xterm", "-e"),
    ]
    for binary, mode in candidates:
        path = _sh.which(binary)
        if path:
            return [path, mode]
    return None


def _creatable(folder: Path) -> bool:
    """True when this folder could be created here.

    Walks up to the nearest directory that exists and asks whether this process
    may write in it -- the same question `mkdir -p` answers. A path whose parent
    is root-owned is therefore reported honestly instead of being called
    unwritable just because the mount point itself is not ours to write.
    """
    p = Path(folder)
    for _ in range(64):
        try:
            if p.is_dir():
                return os.access(str(p), os.W_OK)
        except OSError:
            return False
        if p.parent == p:
            return False
        p = p.parent
    return False


def _mounted_disks(eng) -> list[dict]:
    """Real mounted drives, and the archive folder each one would contribute.

    Read from /proc/mounts so nothing extra has to be installed: a source that is
    not a /dev device is a pseudo filesystem (proc, tmpfs, an AppImage's
    squashfs) and is not somewhere to put an archive. Free space is statvfs, and
    the label comes from /dev/disk/by-label when udev left a link.

    This exists so the settings page can offer a drive to click instead of
    asking for a typed path -- and so it can say which one is already the
    downloads folder rather than offering a button that would do nothing.
    """
    labels: dict[str, str] = {}
    try:
        for link in Path("/dev/disk/by-label").iterdir():
            try:
                labels[str(link.resolve())] = link.name.replace("\\x20", " ")
            except OSError:
                continue
    except OSError:
        pass
    skip_prefix = ("/boot", "/proc", "/sys", "/dev", "/run", "/snap", "/sysroot",
                   "/var/lib/docker", "/var/lib/flatpak")
    # The same btrfs filesystem is mounted many times (ostree subvolumes); those
    # are one drive, not seven, and /etc is not a place to keep an archive.
    skip_exact = {"/etc", "/var", "/usr", "/", "/var/tmp", "/tmp", "/var/home/.cache"}
    roots = []
    for r in (getattr(eng, "roots", None) or []):
        try:
            roots.append(Path(r).resolve())
        except OSError:
            continue
    try:
        out_root = Path(getattr(eng, "output_root", "") or ".").resolve()
    except OSError:
        out_root = Path("/")
    try:
        lines = Path("/proc/mounts").read_text().splitlines()
    except OSError:
        return []
    out: list[dict] = []
    by_device: dict[str, dict] = {}
    for line in lines:
        parts = line.split()
        if len(parts) < 3:
            continue
        source, mount, fstype = parts[0], parts[1].replace("\\040", " "), parts[2]
        if not source.startswith("/dev/"):
            continue
        if mount in skip_exact:
            continue
        if any(mount == s or mount.startswith(s + "/") for s in skip_prefix):
            continue
        try:
            st = os.statvfs(mount)
        except OSError:
            continue
        if st.f_blocks == 0:
            continue
        m = Path(mount)
        try:
            home_r = Path.home().resolve()
        except OSError:
            home_r = Path("/var/home")
        # The machine's own disk cannot hold an archive at its top level: `/` and
        # `/var/home` belong to root, so the only place a folder can be created
        # on it is inside the user's own home directory. It is offered like any
        # other drive rather than hidden -- the same "use this drive" button,
        # pointed at a path this process may actually write.
        is_system_mount = bool(mount == "/" or m == home_r or m in home_r.parents)
        # A root is an Instagram archive folder. The layout is
        # `<mount>/hardlywatching/instagram`, with the older `<mount>/instagram`
        # still read so a drive that predates the wrapper folder keeps working.
        # Whichever of those is ALREADY a root wins, so the page marks the real
        # one instead of offering to add a second copy of the same drive.
        cands = [m / "hardlywatching" / "instagram", m / "instagram"]
        if m.name in ("instagram", "hardlywatching"):
            cands.insert(0, m)
        if is_system_mount:
            cands.append(m / home_r.name / "hardlywatching" / "instagram")
        resolved: list[tuple[Path, Path]] = []
        for c in cands:
            try:
                resolved.append((c, c.resolve()))
            except OSError:
                resolved.append((c, c))
        chosen = next((c for c, r in resolved if r in roots or r == out_root), None)
        if chosen is None:
            chosen = next((c for c, _r in resolved if c.is_dir()), None)
        if chosen is None:
            # Nothing exists yet: take the first candidate this process could
            # actually create, so the row is not offered as unwritable just
            # because the top of the disk is owned by root.
            chosen = next((c for c, _r in resolved if _creatable(c)), resolved[0][0])
        archive = chosen
        try:
            archive_r = archive.resolve()
            mount_r = m.resolve()
        except OSError:
            archive_r, mount_r = archive, m
        total = st.f_blocks * st.f_frsize
        free = st.f_bavail * st.f_frsize
        try:
            has_archive = archive.is_dir()
        except OSError:
            has_archive = False
        is_downloads = archive_r == out_root or mount_r == out_root
        is_archive = archive_r in roots or mount_r in roots
        row = {
            "path": str(m),
            "label": labels.get(str(Path(source).resolve()), "") or m.name,
            "fstype": fstype,
            "total_gb": round(total / 1e9, 1),
            "free_gb": round(free / 1e9, 1),
            "used_pct": round(100.0 * (total - free) / total, 1) if total else 0.0,
            # Writability is asked of the folder that would hold the archive, not
            # of the mount point: a mount whose top level is root-owned is still
            # perfectly usable one level down.
            "writable": os.access(str(archive), os.W_OK) if has_archive
                        else _creatable(archive),
            "archive": str(archive),
            "has_archive": has_archive,
            "is_downloads": bool(is_downloads),
            "is_archive": bool(is_archive),
            # Informational only -- nothing is filtered on it. Two 1 TB disks
            # otherwise read as the same row, and this is what tells them apart.
            "system": is_system_mount,
        }
        # One row per physical device: the same btrfs filesystem is mounted as
        # several subvolumes, and those are one drive. The home mount wins over
        # the rest, and a drive already in use wins over both.
        rank = (not is_downloads, not is_archive, mount not in ("/var/home", "/home"),
                len(mount), mount)
        prev = by_device.get(source)
        if prev is None or rank < prev["_rank"]:
            row["_rank"] = rank
            by_device[source] = row
    for row in by_device.values():
        row.pop("_rank", None)
        out.append(row)
    # The drive in use first, then the emptiest: the one a person reaches for is
    # either already working or has room.
    out.sort(key=lambda d: (not d["is_downloads"], not d["is_archive"], -d["free_gb"]))
    return out


class QuietServer(ThreadingHTTPServer):
    """A threaded server that does not shout when a browser walks away.

    Closing a tab, navigating mid-poll, or a tool cancelling a request closes the
    socket while a response is still being written. socketserver reports that as
    a full traceback ending in BrokenPipeError/ConnectionResetError, which reads
    in the journal exactly like a crash. It is not one, so drop it.
    """

    daemon_threads = True

    def handle_error(self, request, client_address):
        exc = sys.exc_info()[1]
        if isinstance(exc, (BrokenPipeError, ConnectionResetError,
                            ConnectionAbortedError)):
            return
        super().handle_error(request, client_address)


# Zip builds run in their own thread: a big profile takes minutes, and a button
# that says nothing for minutes reads as a hang. The page watches `_ZIPS` through
# /api/profile-zip/progress and starts the download itself when the build lands.
_ZIPS: dict[str, dict] = {}
# A built zip nobody downloaded would otherwise sit in the cache forever; one day
# is long enough to fetch it twice and short enough not to be a space problem.
ZIP_TTL = 24 * 60 * 60


def _zip_dir() -> Path:
    folder = cache_dir() / "zips"
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def purge_zips(max_age: float = ZIP_TTL) -> None:
    """Delete built zips older than a day, and forget their tokens.

    The sweep goes by file mtime rather than only the in-memory table: after a
    restart the table is empty while the files are still on disk, and those
    would otherwise never be reclaimed.
    """
    cutoff = time.time() - max_age
    try:
        entries = list(_zip_dir().iterdir())
    except OSError:
        return
    for entry in entries:
        try:
            if entry.is_file() and entry.stat().st_mtime < cutoff:
                entry.unlink()
        except OSError:
            continue
    for token, info in list(_ZIPS.items()):
        if (info.get("finished") or info.get("started") or 0) < cutoff:
            _ZIPS.pop(token, None)


def build_zip(token: str, plan: list[tuple[Path, str, int]]) -> None:
    """Write `plan` into the zip `token` names, reporting progress as it goes."""
    info = _ZIPS[token]
    tmp = tempfile.NamedTemporaryFile(suffix=".zip", dir=str(_zip_dir()), delete=False)
    tmp.close()
    try:
        # Photos and videos are already compressed: store them, so a multi-GB
        # profile is a straight copy instead of a CPU burn.
        with zipfile.ZipFile(tmp.name, "w", zipfile.ZIP_STORED, allowZip64=True) as zf:
            for path, arc, size in plan:
                try:
                    zf.write(path, arc)
                    info["done"] += 1
                    info["bytes"] += size
                except OSError:
                    continue      # the file went away mid-build; skip it
        info["path"] = tmp.name
        info["finished"] = time.time()
        info["status"] = "ready"
    except OSError as exc:
        info["status"] = "error"
        info["error"] = str(exc)
        try:
            os.unlink(tmp.name)
        except OSError:
            pass


class Handler(BaseHTTPRequestHandler):
    server_version = "InstaQueue/2.0"
    # HTTP/1.1 keeps the socket open between requests. Without it every
    # thumbnail, avatar and tile opened a fresh TCP connection to a Python
    # process -- a profile grid of 149 clips meant 149 handshakes through a
    # handful of threads, which is most of why the grid filled in slowly even
    # on localhost. Every response here sets Content-Length (a 304 has no body
    # by definition), so the framing is unambiguous.
    protocol_version = "HTTP/1.1"
    # An idle kept-alive socket must not pin a thread forever; the page keeps
    # about six open and closes them when the tab goes away.
    timeout = 30

    def log_message(self, fmt, *args):
        pass

    def _json(self, obj, code: int = 200) -> None:
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _json_etagged(self, obj, code: int = 200) -> None:
        """JSON that the browser may revalidate: unchanged state costs ~0 bytes.

        /api/state is polled every 1.2s and is ~2 MB (one entry per job, forever:
        the queue keeps its history). Downloading and parsing that while nothing
        has changed is most of what made the UI feel slow, on the gallery tab as
        much as on the queue -- the gallery only needed the disk line and the
        counts, which never change between polls. The body is still built (that
        is milliseconds and the state has to be read anyway), but an unchanged
        snapshot goes out as a 304 with no body and no parse on the other side.
        """
        body = json.dumps(obj).encode()
        etag = '"' + hashlib.blake2b(body, digest_size=8).hexdigest() + '"'
        if self.headers.get("If-None-Match") == etag:
            self.send_response(304)
            self.send_header("ETag", etag)
            self.send_header("Cache-Control", "no-cache")
            self.end_headers()
            return
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("ETag", etag)
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        self.wfile.write(body)

    def _read_json(self) -> dict:
        try:
            n = int(self.headers.get("Content-Length") or 0)
            if n <= 0:
                return {}
            return json.loads(self.rfile.read(n).decode())
        except Exception:
            return {}

    # ---------- upload ----------

    # A single file is capped so one enormous upload cannot exhaust memory: the
    # body is read into RAM before being written out. Raise via the env var if
    # you ever need to push something bigger.
    MAX_UPLOAD = int(os.environ.get("INSTA_MAX_UPLOAD", 512 * 1024 * 1024))

    def _backup_import(self) -> None:
        """Restore state.json / profiles.db from a backup zip in the body.

        Refuses while anything is downloading: the workers write state.json as
        they go, so a swap underneath them would be undone a second later or
        corrupt the queue. The pre-restore files are themselves backed up first,
        so a restore that turns out to be the wrong zip can be undone the same
        way.
        """
        from urllib.parse import parse_qs
        import backup as _b

        q = parse_qs(urlparse(self.path).query)
        root_arg = (q.get("root") or [""])[0].strip()
        parts = {x.strip() for x in (q.get("parts") or ["state,profiles,session"])[0].split(",")
                 if x.strip()}

        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            n = 0
        if n <= 0:
            return self._json({"ok": False, "error": "Empty upload."}, 400)
        if n > 128 * 1024 * 1024:
            return self._json({"ok": False, "error": "That backup is larger than 128MB."}, 413)

        fd, tmp_name = tempfile.mkstemp(prefix="hw-restore-", suffix=".zip")
        tmp = Path(tmp_name)
        try:
            with os.fdopen(fd, "wb") as fh:
                remaining = n
                while remaining > 0:
                    chunk = self.rfile.read(min(1024 * 1024, remaining))
                    if not chunk:
                        break
                    fh.write(chunk)
                    remaining -= len(chunk)

            eng = get_engine()
            active = [j for j in list(eng.jobs.values())
                      if getattr(j, "status", "") in ("queued", "running", "retrying")]
            if active:
                return self._json({"ok": False, "error":
                                   f"{len(active)} job(s) are queued or running. Clear the "
                                   "queue first — a restore overwrites it."}, 409)

            # Keep what is being replaced, so this is reversible.
            pre = None
            try:
                pre = _b.export_zip(_b.backups_dir() /
                                    ("hw-prerestore-" + time.strftime("%Y%m%d-%H%M%S") + ".zip"),
                                    include_session=False)
            except FileNotFoundError:
                pre = None

            summary = _b.restore(tmp, archive_root=Path(root_arg) if root_arg else None,
                                 wanted=parts)
        except Exception as exc:
            return self._json({"ok": False, "error": str(exc)}, 400)
        finally:
            try:
                tmp.unlink()
            except OSError:
                pass

        reload_engine()
        summary["pre_restore_backup"] = pre.get("path") if pre else ""
        summary["paths"] = _b.paths()
        return self._json(summary)

    def _upload(self) -> None:
        """Accept files from the browser and write them into a profile folder.

        multipart/form-data is parsed here by hand rather than with `cgi`, which
        is gone in Python 3.13+. The body is read whole, split on the boundary,
        and each part's filename and bytes are taken out. Files are written to a
        temporary name in the destination and renamed on success, so an
        interrupted or cancelled upload can never leave a half file that the
        gallery would show as a truncated image.
        """
        ctype = self.headers.get("Content-Type") or ""
        m = re.search(r'boundary="?([^";]+)"?', ctype)
        if "multipart/form-data" not in ctype or not m:
            return self._json({"ok": False,
                               "message": "Expected a multipart upload."}, 400)
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            n = 0
        if n <= 0:
            return self._json({"ok": False, "message": "Empty upload."}, 400)
        if n > self.MAX_UPLOAD:
            return self._json({"ok": False, "message":
                f"That upload is larger than the {self.MAX_UPLOAD // (1024*1024)}MB "
                "limit."}, 413)

        # Stream the body to a scratch file rather than read(n) into RAM: the
        # size cap allows hundreds of MB, and reading it whole doubles that in
        # memory once the boundary split runs. The read here stays bounded to
        # one chunk at a time; the body is then parsed from disk.
        import tempfile
        scratch = tempfile.NamedTemporaryFile(prefix="hw-up-", delete=False)
        scratch_name = scratch.name
        try:
            remaining = n
            while remaining > 0:
                chunk = self.rfile.read(min(1024 * 1024, remaining))
                if not chunk:
                    break
                scratch.write(chunk)
                remaining -= len(chunk)
        finally:
            scratch.close()
        try:
            with open(scratch_name, "rb") as fh:
                raw = fh.read()
        finally:
            try:
                os.unlink(scratch_name)
            except OSError:
                pass
        boundary = b"--" + m.group(1).encode()

        # Parts are: headers, blank line, content. Split on the boundary and
        # keep only the pieces that actually carry a filename.
        profile = ""
        section = "main"
        files: list[tuple[str, bytes]] = []
        for chunk in raw.split(boundary):
            if not chunk or chunk in (b"--", b"--\r\n", b"\r\n"):
                continue
            if b"\r\n\r\n" not in chunk:
                continue
            head, _, content = chunk.partition(b"\r\n\r\n")
            # Trim the CRLF that belongs to the boundary, not the file.
            if content.endswith(b"\r\n"):
                content = content[:-2]
            head_text = head.decode("utf-8", "replace")
            fm = re.search(r'filename="([^"]*)"', head_text)
            nm = re.search(r'name="([^"]*)"', head_text)
            field = nm.group(1) if nm else ""
            if fm is not None:
                name = os.path.basename(fm.group(1) or "")
                if name:
                    files.append((name, content))
            elif field == "profile":
                profile = content.decode("utf-8", "replace").strip()
            elif field == "section":
                section = content.decode("utf-8", "replace").strip() or "main"

        if not files:
            return self._json({"ok": False, "message": "No files in that upload."}, 400)
        if not profile:
            return self._json({"ok": False, "message": "Pick a profile first."}, 400)

        eng = get_engine()
        username = clean_profile_name(profile)
        if not username:
            return self._json({"ok": False, "message": "That profile name is not usable."}, 400)

        # Write into the folder that already holds this profile, so uploading to
        # an existing archive adds to it. A brand new name goes to the root that
        # receives downloads, which must be mounted -- otherwise files would
        # land in a directory that is not there.
        base = eng.root_for(username)
        if base is None:
            root = eng.output_root
            try:
                if not root.is_dir():
                    return self._json({"ok": False, "message":
                        f"{root} is not there right now. Is the drive mounted?"}, 400)
                base = root / username
                base.mkdir(parents=True, exist_ok=True)
            except OSError as e:
                return self._json({"ok": False,
                                   "message": f"Could not create {base}: {e}"}, 400)
        if section in ("favorites", "trash"):
            base = base / section
            try:
                base.mkdir(parents=True, exist_ok=True)
            except OSError as e:
                return self._json({"ok": False,
                                   "message": f"Could not create {base}: {e}"}, 400)

        saved, skipped, failed = [], [], []
        for name, data in files:
            # Only media the gallery can actually display, and never a path.
            if name != os.path.basename(name):
                failed.append((name, "unusable filename"))
                continue
            if os.path.splitext(name)[1].lower() not in UPLOAD_EXTS:
                skipped.append(name)
                continue
            dest = base / name
            # Do not silently overwrite something already archived: keep both,
            # with a suffix, so an upload can never destroy a download.
            if dest.exists():
                stem, ext = os.path.splitext(name)
                k = 2
                while (base / f"{stem}_{k}{ext}").exists() and k < 1000:
                    k += 1
                dest = base / f"{stem}_{k}{ext}"
            tmp = base / (dest.name + ".uploading")
            try:
                tmp.write_bytes(data)
                tmp.replace(dest)      # atomic: appears complete or not at all
                saved.append(dest.name)
            except OSError as e:
                failed.append((name, str(e)))
                try:
                    tmp.unlink()
                except OSError:
                    pass

        # The folder changed, so the listing cache for it is now wrong.
        _cache.drop(str(base))
        _media_cache_forget(base)

        return self._json({"ok": bool(saved), "profile": username,
                           "saved": saved, "skipped": skipped,
                           "failed": [{"file": f, "why": w} for f, w in failed],
                           "section": section})

    def _plan_zip(self, name: str) -> list[tuple[Path, str, int]]:
        """The files that belong in `name`'s zip, and their arc names.

        The folder in the gallery is the archive itself, so this is just a walk:
        `<root>/<handle>` for Instagram, `<parent>/tiktok/<handle>` for TikTok. A
        handle on both sites is one card, so it is one zip with `instagram/` and
        `tiktok/` inside; on a single site the handle is the archive's root
        folder. 0-byte files are the marker a deleted post leaves behind, not
        content, so they are skipped.
        """
        eng = get_engine()
        folders = []
        for platform in ("instagram", "tiktok"):
            folder = eng.root_for(name, platform)
            if folder is not None and folder.is_dir():
                folders.append((platform, folder))
        plan = []
        for platform, folder in folders:
            for path in sorted(folder.rglob("*")):
                if not path.is_file():
                    continue
                try:
                    size = path.stat().st_size
                except OSError:
                    continue
                if size == 0:
                    continue
                rel = path.relative_to(folder).as_posix()
                arc = f"{name}/{rel}" if len(folders) == 1 \
                    else f"{name}/{platform}/{rel}"
                plan.append((path, arc, size))
        return plan

    def _start_zip(self, name: str, wait: bool = False) -> str | None:
        """Begin building `name`'s zip; the page polled for progress gets the token."""
        purge_zips()
        plan = self._plan_zip(name)
        if not plan:
            self._json({"error": "nothing on disk for that profile"}, 404)
            return None
        token = secrets.token_urlsafe(9)
        _ZIPS[token] = {"status": "building", "name": name, "done": 0,
                        "files": len(plan), "bytes": 0,
                        "total": sum(item[2] for item in plan),
                        "path": None, "error": None, "started": time.time()}
        if wait:
            build_zip(token, plan)
        else:
            threading.Thread(target=build_zip, args=(token, plan), daemon=True).start()
        return token

    def _zip_progress(self, token: str) -> None:
        """How far along a build is, in files and bytes, for the button's label."""
        purge_zips()
        info = _ZIPS.get(token)
        if info is None:
            # The token aged out or the app restarted: the page stops polling and
            # says so, rather than watching a build that no longer exists.
            return self._json({"status": "unknown"}, 404)
        total = info["total"] or 0
        pct = 100 if info["status"] == "ready" else (
            int(info["bytes"] * 100 / total) if total else 0)
        self._json({"status": info["status"], "done": info["done"],
                    "files": info["files"], "bytes": info["bytes"],
                    "total": total, "pct": pct, "error": info.get("error")})

    def _send_ready_zip(self, token: str) -> None:
        """Serve a finished build.

        The file is left on disk after the send: it is swept a day later, so a
        second click in the same sitting downloads the same bytes instead of
        re-reading the whole profile.
        """
        info = _ZIPS.get(token)
        if info is None:
            return self.send_error(404)
        if info["status"] != "ready" or not info.get("path"):
            return self._json({"status": info["status"]}, 409)
        path = Path(info["path"])
        try:
            size = path.stat().st_size
        except OSError:
            return self.send_error(410)
        self.send_response(200)
        self.send_header("Content-Type", "application/zip")
        self.send_header("Content-Disposition",
                         'attachment; filename="%s.zip"' % info["name"])
        self.send_header("Content-Length", str(size))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        try:
            with open(path, "rb") as fh:
                shutil.copyfileobj(fh, self.wfile, 1024 * 1024)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _send_profile_zip(self, name: str) -> None:
        """Direct URL: build and serve in one request, no progress to report."""
        token = self._start_zip(name, wait=True)
        if token:
            self._send_ready_zip(token)

    def _serve_file(self, path: Path, cache: bool = False) -> None:
        if not path.is_file():
            self.send_error(404)
            return
        ctype = mimetypes.guess_type(str(path))[0] or "application/octet-stream"
        size = path.stat().st_size

        # Honour a single byte range so a video can be seeked: the browser asks
        # for `bytes=N-` and expects 206 with Content-Range. Without this the
        # whole clip streams from the start, so scrubbing does nothing.
        start, end, status = 0, size - 1, 200
        rng = self.headers.get("Range") or ""
        if rng.startswith("bytes="):
            m = re.match(r"bytes=(\d*)-(\d*)$", rng.split(",")[0].strip())
            if m:
                a, b = m.group(1), m.group(2)
                if a == "" and b and int(b) > 0:
                    # suffix form `bytes=-N`: the last N bytes
                    start, end, status = max(0, size - int(b)), size - 1, 206
                elif a != "":
                    start = int(a)
                    end = min(int(b), size - 1) if b else size - 1
                    if 0 <= start <= end < size:
                        status = 206

        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self.send_header("Content-Length", str(end - start + 1))
        else:
            self.send_header("Content-Length", str(size))
        self.send_header("Cache-Control",
                         "private, max-age=86400" if cache else "no-store")
        self.end_headers()
        # Stream in fixed chunks. `shutil.copyfileobj(fh, wfile, length=window)`
        # reads the WHOLE window into memory before the first byte goes out --
        # a 400 MB allocation for a big clip, and a delay a browser cannot play
        # through. A player can only start on bytes it has already received, so
        # send the first chunk first and keep the window small.
        remaining = end - start + 1
        with open(path, "rb") as fh:
            fh.seek(start)
            while remaining > 0:
                chunk = fh.read(min(256 * 1024, remaining))
                if not chunk:
                    break
                self.wfile.write(chunk)
                remaining -= len(chunk)

