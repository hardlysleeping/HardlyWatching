def _opt(flag: str, env: str, default: str) -> str:
    """Value for a setting: --flag on the command line beats the env var."""
    argv = sys.argv[1:]
    if flag in argv:
        i = argv.index(flag)
        if i + 1 < len(argv):
            return argv[i + 1]
    return os.environ.get(env, default)


