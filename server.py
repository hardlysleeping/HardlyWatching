def _profile_list_param(raw) -> list[str]:
    """The handles out of a comma-separated `profiles=` query value.

    The timeline picker sends several names at once; `profile` (exactly one) is
    still accepted everywhere. Anything that is not a plausible handle is
    dropped here rather than handed to the folder walk.
    """
    from urllib.parse import unquote
    values = raw if isinstance(raw, list) else ([raw] if raw else [])
    out: list[str] = []
    for value in values:
        for part in str(value or "").split(","):
            name = clean_profile_name(unquote(part.strip()))
            if name and name not in out:
                out.append(name)
    return out[:200]


def _page_args(q, default_limit: int = 0, cap: int = 2000) -> tuple[int, int]:
    """(limit, offset) from a query, for the endpoints that can be paged.

    `limit=0` (the default, and what happens when the parameter is absent) means
    "the whole list", so every existing caller -- and the UI as it stands --
    keeps getting exactly the response it got before. A caller that draws a page
    at a time can ask for one and skip the rest of the payload.
    """
    def _int(name: str, fallback: int) -> int:
        try:
            return int((q.get(name) or [str(fallback)])[0] or fallback)
        except (TypeError, ValueError):
            return fallback
    limit = _int("limit", default_limit)
    offset = max(0, _int("offset", 0))
    if limit > 0:
        limit = min(limit, cap)
    return max(0, limit), offset


def _tag_path_parts(eng, path: str) -> dict | None:
    """Turn a stored media path back into (profile, platform, section, file).

    Tags are keyed by absolute path, which is right for the pass -- it is the one
    name a file has regardless of which section or root it lives in. The gallery
    needs the other spelling, so this walks the roots the engine already knows and
    returns what /thumb and /media expect. A path under a root that has since gone
    away returns None: the tag stays, the tile is simply not offered.
    """
    p = Path(path)
    for root in eng.roots:
        for plat in ("instagram", "tiktok"):
            try:
                base = eng._platform_folder(root, plat)
            except Exception:
                continue
            try:
                rel = p.relative_to(base)
            except (ValueError, TypeError):
                continue
            parts = rel.parts
            if len(parts) < 2:
                continue
            handle, rest = parts[0], list(parts[1:])
            section = "main"
            if rest and rest[0] in ("favorites", "trash"):
                section = rest.pop(0)
            if len(rest) > 1 and rest[0] == handle:
                rest.pop(0)                     # <handle>/<handle>/... layout
            if not rest:
                continue
            return {"profile": handle, "platform": plat, "section": section,
                    "file": "/".join(rest)}
    return None


def _tag_posts(eng, paths: list[str]) -> list[dict]:
    """Tagged media as gallery posts, so a tag filter is the normal grid.

    The point of the filter is not to look at matches, it is to act on them:
    clicking "male" has to give tiles that can be selected and trashed like any
    other tile. So the files are grouped back into posts (carousel parts under
    one tile, as everywhere else) and returned in exactly the shape
    /api/gallery/all already produces.
    """
    import time as _t
    groups: dict[tuple, dict] = {}
    for path in paths:
        where = _tag_path_parts(eng, path)
        if not where:
            continue
        name = where["file"].rsplit("/", 1)[-1]
        # 2019-01-07_21-24-56_UTC_2.jpg -> base 2019-01-07_21-24-56_UTC, so the
        # carousel parts stay one post with several items. Splitting on the
        # first "_" (the date) would have merged a whole day into one tile.
        stem, dot, ext = name.rpartition(".")
        base = re.sub(r"_\d+$", "", stem or name)
        key = (where["profile"].lower(), where["platform"], where["section"], base)
        g = groups.setdefault(key, {"username": where["profile"],
                                    "platform": where["platform"],
                                    "section": where["section"],
                                    "items": [], "_names": set()})
        if name in g["_names"]:
            continue
        g["_names"].add(name)
        g["items"].append({"file": name,
                           "kind": "video" if dot and ext.lower() in
                                   ("mp4", "mov", "webm", "m4v") else "image"})
    out = []
    for g in groups.values():
        g.pop("_names", None)
        g["items"].sort(key=lambda i: i["file"])
        first = g["items"][0]["file"]
        stamp = ""
        try:
            stamp = _t.strftime("%Y-%m-%d", _t.strptime(first[:10], "%Y-%m-%d"))
        except Exception:
            stamp = ""
        g["count"] = len(g["items"])
        g["date"] = stamp
        g["post"] = first
        g["ts"] = 0
        g["ts_src"] = "name" if stamp else ""
        out.append(g)
    out.sort(key=lambda p: (p.get("date") or "", p["username"]), reverse=True)
    return out


def _mark_bookmarks(posts, profile: str | None = None) -> list[dict]:
    """Mark which of these posts are already saved, with the category each is in.

    Every view that draws tiles needs this, or the bookmark button lies: a post
    saved from Shorts showed an empty button in its profile's grid. One query for
    the whole list rather than one per tile.
    """
    try:
        keys = _profile_db().bookmark_keys()
    except Exception:
        return posts
    for p in posts:
        items = p.get("items") or []
        if not items or not items[0].get("file"):
            continue
        who = (profile or p.get("username") or "").strip().lower()
        key = (who, items[0]["file"])
        if key in keys:
            cats = keys[key]
            p["bookmarked"] = 1
            p["categories"] = cats
            p["category"] = cats[0] if cats else None
    return posts


