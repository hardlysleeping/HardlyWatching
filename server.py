    def _refuse_remote(self, path: str) -> None:
        """Answer a request from another machine while the toggle is off.

        Deliberately explicit rather than a bare 403: someone who typed this
        address on a phone needs to know the app is running and which switch
        turns it on, not that the server is broken.
        """
        # The body of a refused POST is never read, so this connection cannot be
        # reused: whatever is left in the socket would be parsed as the next
        # request line. HTTP/1.1 makes that a hang instead of a close.
        self.close_connection = True
        if path.startswith("/api/"):
            return self._json({"ok": False, "error": "lan_disabled",
                               "message": "Phone access is off. Turn on "
                                          "\"Reachable from your phone\" in "
                                          "Settings on the computer."}, 403)
        page = (
            "<!doctype html><meta charset=utf-8><title>HardlyWatching</title>"
            "<body style=\"font:16px system-ui;max-width:34em;margin:12vh auto;"
            "padding:0 1.5em;line-height:1.5\">"
            "<h1 style=\"font-size:1.2em\">HardlyWatching is running</h1>"
            "<p>This device is not allowed to use it yet.</p>"
            "<p>On the computer running it, open <b>Settings \u2192 Open on your "
            "phone</b> and turn on <b>Reachable from your phone</b>.</p>")
        body = page.encode("utf-8")
        self.send_response(403)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:
        p = urlparse(self.path).path
        if not _lan_gate_allows(self.client_address[0], _lan_enabled()):
            return self._refuse_remote(p)
        if p in ("/", "/index.html"):
            return self._serve_file(HERE / "index.html")
        if p in ("/shorts", "/shorts/"):
            # Phone-shaped feed. Served from the same app so it shares the
            # output root, the state file and the clips table.
            return self._serve_file(HERE / "shorts.html")
        if p == "/shorts.webmanifest":
            return self._serve_file(HERE / "shorts.webmanifest")
        if p == "/app.webmanifest":
            # The maniest the installed phone app uses. It opens / and not
            # /shorts: the standalone /shorts page has no tabs, so there was no
            # way back out of it and nothing to swap to. Opening the app gives
            # Shorts as a tab like Gallery, which is what was asked for.
            return self._serve_file(HERE / "app.webmanifest")
        # Icons. Files rather than data URLs, because that is what a launcher,
        # an iOS home screen and a tab strip all read. Generated by make_icons.py
        # from the same mark the manifests used to inline.
        if p in ICON_ROUTES:
            return self._serve_file(HERE / ICON_ROUTES[p], cache=True)
        if p == "/api/autostart":
            # Read-only: whether the service starts itself at login.
            return self._json(autostart_state())
        if p == "/api/static":
            # Progress of the static-video scan, polled while it runs.
            return self._json(static_status())
        if p == "/api/exclusions":
            # Who is excluded, both platforms. Small and JSON, so the settings
            # group and the delete dialog can both read it. Same store the
            # engine consults on every add, so this list is the truth.
            try:
                db = _profile_db()
                rows = []
                for plat in ("instagram", "tiktok"):
                    for r in db.excluded_list(plat):
                        rows.append({"profile": r["handle"],
                                     "platform": plat,
                                     "reason": r.get("reason") or "",
                                     "excluded_at": r.get("excluded_at") or 0})
            except Exception as e:
                return self._json({"ok": False, "error": str(e), "count": 0,
                                   "profiles": []})
            rows.sort(key=lambda r: r["excluded_at"], reverse=True)
            return self._json({"ok": True, "count": len(rows), "profiles": rows})
        if p == "/api/profile/totals":
            # How many files and bytes a delete would move, counted the same way
            # the delete counts them. The dialog quotes these numbers, so it
            # cannot promise one figure and report another.
            from urllib.parse import parse_qs as _pq
            q = _pq(urlparse(self.path).query)
            prof = str((q.get("profile") or [""])[0]).strip().lstrip("@")
            plat = "tiktok" if (q.get("platform") or [""])[0] == "tiktok" else "instagram"
            if not prof:
                return self._json({"ok": False, "error": "no profile given"})
            return self._json(get_engine().profile_totals(prof, plat))
        if p == "/api/tiktok/browsers":
            # Which browsers are signed into TikTok (yt-dlp takes a name, not a
            # cookie file, so this is a plain list).
            return self._json({"browsers": get_engine().tiktok_browsers()})
        if p.startswith("/api/shorts/file/"):
            # Stream a clip from the archive. resolve() refuses anything that
            # escapes the output root, so a traversal attempt 404s.
            import shorts
            rel = p[len("/api/shorts/file/"):]
            from urllib.parse import unquote
            target = shorts.resolve(get_engine().output_root, unquote(rel))
            if target is None:
                return self.send_error(404)
            return self._serve_file(target, cache=True)
        if p == "/api/state":
            # The UI polls this every ~1.2s, so it doubles as a worker watchdog:
            # if the worker died with work still queued, revive it.
            get_engine().watchdog()
            snap = get_engine().snapshot()
            # `?lite=1` is what the poller asks for while the gallery or shorts
            # tab is on screen: those views need the drive line, the counts and
            # the run state, and NOT the 2,448-job queue (2 MB) they cannot even
            # display. Same snapshot, one key dropped; the client keeps the jobs
            # it already has and asks for the full one when the queue is shown.
            from urllib.parse import parse_qs as _pq
            if (_pq(urlparse(self.path).query).get("lite") or [""])[0] in ("1", "true"):
                snap.pop("jobs", None)
            snap["roots"] = get_engine().roots_status()
            # Surface the on-disk listing cache so its state is inspectable
            # rather than a silent performance mystery.
            snap["cache"] = _cache.stats()
            # Whether TikTok has a session of its own, and which of the two the
            # next download will use. This was invisible before, which is how it
            # came to look like TikTok simply had no session.
